#!/usr/bin/env node
// Database helper — reads SUPABASE_DB_URL from .env.local (never printed).
//   npm run db:push    apply pending migrations in supabase/migrations
//   npm run db:types   regenerate src/types/database.ts from the live schema
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const CLI = ["--yes", "supabase@3.4.0"];

function readDbUrl() {
  let text;
  try {
    text = readFileSync(".env.local", "utf8");
  } catch {
    fail("No .env.local file. Copy .env.example to .env.local and fill it in.");
  }
  const line = text.split(/\r?\n/).find((l) => l.startsWith("SUPABASE_DB_URL="));
  const url = line?.slice("SUPABASE_DB_URL=".length).trim();
  if (!url) fail("SUPABASE_DB_URL is empty in .env.local (Supabase → Connect → Session pooler).");
  return url;
}

function fail(message) {
  console.error(`✖ ${message}`);
  process.exit(1);
}

/** Hide connection strings in any CLI output. */
function mask(text) {
  return text.replace(/postgres(ql)?:\/\/\S+/g, "postgresql://***");
}

/**
 * Runs npx through Node directly (no shell): the connection string contains a
 * password, and a shell could misinterpret characters such as & | ^ < >.
 * `npm run` sets npm_execpath to npm-cli.js; npx-cli.js sits next to it.
 */
function npxCommand() {
  const npmCli = process.env.npm_execpath;
  if (!npmCli) fail("Run this through npm: npm run db:push / npm run db:types");
  return [process.execPath, [join(dirname(npmCli), "npx-cli.js")]];
}

function runCli(args, { capture = false } = {}) {
  const [node, prefix] = npxCommand();
  const result = spawnSync(node, [...prefix, ...CLI, ...args], { encoding: "utf8" });
  if (!capture || result.status !== 0) {
    process.stdout.write(mask(result.stdout ?? ""));
    process.stderr.write(mask(result.stderr ?? "").replace(/Warning: --db-url is deprecated[^\n]*\n?/, ""));
  }
  if (result.status !== 0) process.exit(result.status ?? 1);
  return result.stdout;
}

const command = process.argv[2];
const url = readDbUrl();

if (command === "push") {
  runCli(["db", "push", "--db-url", url, "--yes"]);
} else if (command === "types") {
  const types = runCli(["gen", "types", "typescript", "--db-url", url, "--schema", "public"], { capture: true });
  writeFileSync("src/types/database.ts", `// Generated by \`npm run db:types\` - do not edit by hand.\n${types.replace(/\r\n/g, "\n")}`);
  console.log("✓ src/types/database.ts regenerated");
} else {
  fail("Usage: node scripts/db.mjs <push|types>");
}
